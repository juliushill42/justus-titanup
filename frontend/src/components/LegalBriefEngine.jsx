'use client';
// LegalBriefEngine — Affidavit drafting + backend /draft endpoint
// Julius Cameron Hill | JCH-2026 | Titan Universal AI LLC
import { useState, useCallback } from "react";
import { FileText, Send, Copy, Download, CheckCircle, Gavel } from "lucide-react";

const JURISDICTIONS = [
  "Federal District Court",
  "U.S. Supreme Court",
  "Georgia – State Superior Court",
  "California – Superior Court",
  "New York – Supreme Court",
  "Texas – District Court",
  "Florida – Circuit Court",
  "Illinois – Circuit Court",
];

const BRIEF_TYPES = [
  { id: "affidavit",   label: "Affidavit" },
  { id: "motion",      label: "Motion to Suppress" },
  { id: "complaint",   label: "§1983 Civil Rights Complaint" },
  { id: "habeas",      label: "Habeas Corpus Petition" },
  { id: "injunction",  label: "TRO / Injunction" },
];

function Field({ label, children }) {
  return (
    <div className="flex flex-col gap-1.5">
      <label className="text-[10px] font-bold uppercase text-white/40 tracking-wide">{label}</label>
      {children}
    </div>
  );
}

const inputCls = "bg-white/5 border border-white/10 rounded-xl px-4 py-3 text-sm text-white placeholder-white/20 outline-none focus:border-teal-500/40 transition-colors";

export default function LegalBriefEngine({ api }) {
  const [form, setForm] = useState({
    type:         "affidavit",
    name:         "",
    facts:        "",
    jurisdiction: "Federal District Court",
    relief:       "",
  });
  const [doc,      setDoc]      = useState("");
  const [loading,  setLoading]  = useState(false);
  const [error,    setError]    = useState("");
  const [copied,   setCopied]   = useState(false);

  const set = useCallback((k, v) => setForm(p => ({ ...p, [k]: v })), []);

  const generateBrief = useCallback(async () => {
    if (!form.name.trim() || !form.facts.trim()) {
      setError("Name and facts are required.");
      return;
    }
    setError("");
    setLoading(true);
    setDoc("");

    try {
      // Try backend /draft endpoint
      const res = await fetch(`${api}/draft`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          name:         form.name,
          facts:        form.facts,
          jurisdiction: form.jurisdiction,
          type:         form.type,
          relief:       form.relief,
        }),
      });

      if (res.ok) {
        const data = await res.json();
        setDoc(data.doc || data.document || "");
        return;
      }
    } catch { /* fallback below */ }

    // Sovereign offline generation
    const ts    = new Date().toLocaleString("en-US", { timeZoneName: "short" });
    const label = BRIEF_TYPES.find(b => b.id === form.type)?.label || "AFFIDAVIT";

    const offline = `${label.toUpperCase()}

JURISDICTION: ${form.jurisdiction}
DATE: ${ts}

IN THE MATTER OF: ${form.name.toUpperCase()}

─────────────────────────────────────────────
STATEMENT OF FACTS
─────────────────────────────────────────────

${form.facts.trim()}

─────────────────────────────────────────────
CONSTITUTIONAL BASIS
─────────────────────────────────────────────

${form.type === "motion"
  ? "This motion is made pursuant to the Fourth Amendment to the United States Constitution and Federal Rule of Criminal Procedure 12(b)(3)(C), challenging the lawfulness of the search and seizure."
  : form.type === "complaint"
  ? "This complaint is filed pursuant to 42 U.S.C. § 1983 and the Fourteenth Amendment, alleging deprivation of constitutional rights under color of state law."
  : form.type === "habeas"
  ? "This petition is filed pursuant to 28 U.S.C. § 2254 / § 2255, challenging the constitutionality of the petitioner's detention."
  : form.type === "injunction"
  ? "Petitioner seeks a Temporary Restraining Order and/or Preliminary Injunction pursuant to Fed. R. Civ. P. 65, demonstrating likelihood of success on the merits and irreparable harm."
  : "I, the undersigned, declare under penalty of perjury under the laws of the United States of America that the foregoing is true and correct to the best of my knowledge and belief."
}

${form.relief.trim() ? `─────────────────────────────────────────────
RELIEF REQUESTED
─────────────────────────────────────────────

${form.relief.trim()}` : ""}

─────────────────────────────────────────────
SIGNATURE
─────────────────────────────────────────────

Executed on ${ts}

_________________________________
${form.name}

[Generated by JustUs AI | Titan Universal AI LLC | JCH-2026]
[DRAFT — Consult licensed counsel before filing]`;

    setDoc(offline);
    setLoading(false);
  }, [form, api]);

  const copyDoc = useCallback(() => {
    navigator.clipboard.writeText(doc).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    });
  }, [doc]);

  const downloadDoc = useCallback(() => {
    const blob = new Blob([doc], { type: "text/plain" });
    const url  = URL.createObjectURL(blob);
    const a    = document.createElement("a");
    a.href     = url;
    a.download = `justus-brief-${Date.now()}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  }, [doc]);

  return (
    <div className="flex flex-col gap-6 max-w-3xl">
      {/* Header */}
      <div className="flex items-center gap-3">
        <Gavel className="w-5 h-5 text-teal-400" />
        <div>
          <h2 className="text-sm font-black uppercase tracking-tight">Legal Brief Engine</h2>
          <p className="text-xs text-white/30">Sovereign document drafting · Offline-capable · FRE-compliant output</p>
        </div>
      </div>

      {/* Brief type selector */}
      <Field label="Document Type">
        <div className="flex flex-wrap gap-2">
          {BRIEF_TYPES.map(b => (
            <button key={b.id} onClick={() => set("type", b.id)}
              className={`px-3 py-1.5 rounded-xl text-xs font-bold transition-colors ${
                form.type === b.id
                  ? "bg-teal-500/20 text-teal-400 border border-teal-500/30"
                  : "bg-white/5 text-white/30 hover:text-white/60 border border-white/5"
              }`}>{b.label}</button>
          ))}
        </div>
      </Field>

      <Field label="Your Full Legal Name">
        <input value={form.name} onChange={e => set("name", e.target.value)}
          placeholder="Julius Cameron Hill" className={inputCls} />
      </Field>

      <Field label="Jurisdiction">
        <select value={form.jurisdiction} onChange={e => set("jurisdiction", e.target.value)}
          className={inputCls + " cursor-pointer"}>
          {JURISDICTIONS.map(j => <option key={j} value={j}>{j}</option>)}
        </select>
      </Field>

      <Field label="Statement of Facts">
        <textarea value={form.facts} onChange={e => set("facts", e.target.value)} rows={6}
          placeholder="Describe the incident in detail: date, time, location, officers involved (badge numbers if known), sequence of events, witnesses…"
          className={inputCls + " resize-y"} />
      </Field>

      <Field label="Relief Requested (optional)">
        <textarea value={form.relief} onChange={e => set("relief", e.target.value)} rows={3}
          placeholder="E.g. Suppression of all evidence obtained during unlawful search; monetary damages under §1983…"
          className={inputCls + " resize-y"} />
      </Field>

      {error && <p className="text-xs text-red-400">{error}</p>}

      <button onClick={generateBrief} disabled={loading}
        className="flex items-center justify-center gap-2 bg-teal-500 hover:bg-teal-400 disabled:opacity-40 text-black font-black text-xs uppercase py-3 rounded-xl transition-colors">
        <Send className="w-3.5 h-3.5" />
        {loading ? "Generating…" : "Generate Document"}
      </button>

      {/* Output */}
      {doc && (
        <div className="flex flex-col gap-3">
          <div className="flex items-center justify-between">
            <div className="flex items-center gap-2 text-xs text-green-400">
              <CheckCircle className="w-3.5 h-3.5" />
              Document generated
            </div>
            <div className="flex gap-2">
              <button onClick={copyDoc}
                className="flex items-center gap-1.5 text-xs font-bold text-white/40 hover:text-white/70 border border-white/10 hover:border-white/20 px-3 py-1.5 rounded-xl transition-colors">
                {copied ? <CheckCircle className="w-3 h-3 text-green-400" /> : <Copy className="w-3 h-3" />}
                {copied ? "Copied" : "Copy"}
              </button>
              <button onClick={downloadDoc}
                className="flex items-center gap-1.5 text-xs font-bold text-teal-400 hover:text-teal-300 border border-teal-500/20 hover:border-teal-500/40 px-3 py-1.5 rounded-xl transition-colors">
                <Download className="w-3 h-3" />
                Download
              </button>
            </div>
          </div>

          <pre className="bg-black/40 border border-white/5 rounded-2xl p-5 text-xs text-white/70 font-mono whitespace-pre-wrap leading-relaxed overflow-x-auto">
            {doc}
          </pre>

          <p className="text-[10px] text-white/20 text-center">
            DRAFT ONLY — This document does not constitute legal advice. Consult a licensed attorney before filing.
          </p>
        </div>
      )}
    </div>
  );
}
